-- so solarcommon.ant_patterns_to_regexps() can also be parallel safe
ALTER FUNCTION solarcommon.ant_pattern_to_regexp(text) PARALLEL SAFE;

/**
 * Convert a list of Ant path patterns into regular expressions.
 *
 * This is immutable, so it can be used for a generated column.
 *
 * @param pats the Ant path patterns to convert
 * @returns the equivalent regular expressions
 * @see solarcommon.ant_pattern_to_regexp()
 */
CREATE OR REPLACE FUNCTION solarcommon.ant_patterns_to_regexps(pats text[])
RETURNS text[] LANGUAGE SQL STRICT IMMUTABLE PARALLEL SAFE AS
$$
	SELECT ARRAY(SELECT solarcommon.ant_pattern_to_regexp(p) FROM unnest(pats) p);
$$;

/**
 * Grants that allow another user's datum stream aliases to resolve to a user's datum streams.
 *
 * The grants are enforced by `solardatm.da_datm_alias_allowed()`, which only ever applies a grant
 * to the nodes its owner currently owns. `NULL` is the only wildcard: at least one of `node_ids` and
 * `source_ids` must be given, and neither may be an empty array.
 *
 * @column user_id 			the owner of the streams (the grantor)
 * @column id 				primary key
 * @column created 			the creation date
 * @column modified 		the modification date
 * @column enabled 			true if this grant is active
 * @column allow_public 	true if aliases on public nodes may resolve, which makes the streams
 *                      	readable by anyone
 * @column grantee_id 		the ID of the user wanting access to the owner's streams
 * @column node_ids 		the node IDs to grant, or `NULL` for any node
 * @column source_ids 		the source ID patterns to grant, or `NULL` for any source
 * @column source_regexps 	`source_ids` compiled to regular expressions
 */
CREATE TABLE solaruser.da_datm_alias_grant (
	user_id				BIGINT NOT NULL,
	id					BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	created				TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
	modified			TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
	enabled				BOOLEAN NOT NULL DEFAULT FALSE,
	allow_public		BOOLEAN NOT NULL DEFAULT FALSE,
	grantee_id			BIGINT NOT NULL,
	node_ids			BIGINT[],
	source_ids			CHARACTER VARYING(64)[],
	source_regexps		TEXT[] GENERATED ALWAYS AS (solarcommon.ant_patterns_to_regexps(source_ids::TEXT[])) STORED,
	CONSTRAINT da_datm_alias_grant_pk PRIMARY KEY (user_id, id),
	CONSTRAINT da_datm_alias_grant_chk CHECK (
		(node_ids IS NOT NULL OR source_ids IS NOT NULL)
		AND (node_ids IS NULL OR cardinality(node_ids) > 0)
		AND (source_ids IS NULL OR cardinality(source_ids) > 0)),
	CONSTRAINT da_datm_alias_grant_self_chk CHECK (user_id <> grantee_id),
	CONSTRAINT da_datm_alias_grant_user_fk FOREIGN KEY (user_id)
		REFERENCES solaruser.user_user (id) MATCH SIMPLE
		ON UPDATE NO ACTION ON DELETE CASCADE,
	CONSTRAINT da_datm_alias_grant_grantee_fk FOREIGN KEY (grantee_id)
		REFERENCES solaruser.user_user (id) MATCH SIMPLE
		ON UPDATE NO ACTION ON DELETE CASCADE
);

CREATE INDEX da_datm_alias_grant_grantee_idx ON solaruser.da_datm_alias_grant (grantee_id, user_id);


