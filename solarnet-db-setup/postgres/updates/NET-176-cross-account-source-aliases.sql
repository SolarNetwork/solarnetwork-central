/******************************************************************************
 * TRIGGER function that automatically transfers rows related to a user_node to
 * the new owner when the user_id value is changed. Expected record is
 * solaruser.user_node.
 */
CREATE OR REPLACE FUNCTION solaruser.node_ownership_transfer()
	RETURNS "trigger"  LANGUAGE 'plpgsql' VOLATILE AS $$
BEGIN
	UPDATE solaruser.user_node_conf
	SET user_id = NEW.user_id
	WHERE user_id = OLD.user_id
		AND node_id = NEW.node_id;

	-- a transferred node leaves the alias grants of its old owner, so they do not apply again if
	-- the node is ever returned; access does not depend on this
	DELETE FROM solaruser.da_datm_alias_grant
	WHERE user_id = OLD.user_id
		AND NEW.node_id = ANY(node_ids)
		AND cardinality(array_remove(node_ids, NEW.node_id)) = 0;

	UPDATE solaruser.da_datm_alias_grant
	SET node_ids = array_remove(node_ids, NEW.node_id), modified = CURRENT_TIMESTAMP
	WHERE user_id = OLD.user_id
		AND NEW.node_id = ANY(node_ids);

	RETURN NEW;
END;
$$;

/**
 * View combining user ID with da_datm_meta and the da_datm_alias rows that may resolve, to ease
 * querying. The user ID of an alias is the owner of the alias node, not of the original node.
 */
CREATE OR REPLACE VIEW solaruser.da_datm_meta_aliased AS
SELECT un.user_id
	, s.stream_id
	, s.node_id
	, s.source_id
	, s.names_i
	, s.names_a
	, s.names_s
	, s.jdata
	, s.stream_id AS orig_stream_id
	, FALSE AS is_alias
	, s.created
	, s.updated
FROM solardatm.da_datm_meta s
INNER JOIN solaruser.user_node un ON un.node_id = s.node_id
UNION ALL
SELECT un.user_id
	, a.stream_id
	, a.alias_node_id AS node_id
	, a.alias_source_id AS source_id
	, s.names_i
	, s.names_a
	, s.names_s
	, s.jdata
	, s.stream_id AS orig_stream_id
	, TRUE AS is_alias
	, a.created
	, a.modified AS updated
FROM solardatm.da_datm_alias a
INNER JOIN solardatm.da_datm_meta s ON s.node_id = a.node_id AND s.source_id = a.source_id
INNER JOIN solaruser.user_node un ON un.node_id = a.alias_node_id
WHERE solardatm.da_datm_alias_allowed(a.node_id, a.source_id::TEXT, a.alias_node_id)
;
